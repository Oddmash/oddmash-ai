import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { runtimeGuidance } from './agent-skill-guidance.mjs';

const roleSources = {
  reviewer: ['code-review-collaboration'],
  impact: ['product-planning', 'Impact'],
  triage: ['product-planning', 'Triage'],
  qa: ['quality-assurance'],
  release: ['release-management'],
  docs: ['developer-documentation'],
  architect: ['technical-architecture']
};

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  throw new Error('Use node scripts/bundle-agent-skills.mjs [--check]');
}

const checkout = fileURLToPath(new URL('../', import.meta.url));
const { schemaVersion, revision } = JSON.parse(readFileSync(new URL('./agent-skill-source.json', import.meta.url), 'utf8'));
if (schemaVersion !== 1 || typeof revision !== 'string' || !/^[a-f0-9]{40}$/.test(revision)) {
  throw new Error('Expected a version 1 catalog source manifest with a full commit SHA');
}
const git = (...args) => execFileSync('git', ['-C', checkout, ...args], { encoding: 'utf8', maxBuffer: 100_000 });
if (git('cat-file', '-t', revision).trim() !== 'commit') throw new Error('Catalog revision must identify a commit');
git('merge-base', '--is-ancestor', revision, 'HEAD');

const roles = Object.fromEntries(Object.entries(roleSources).map(([role, [name, section]]) => {
  const path = `catalog/skills/oddmash-${name}/SKILL.md`;
  const markdown = git('show', `${revision}:${path}`);
  return [role, { path, text: runtimeGuidance(markdown, section, path) }];
}));
const output = new URL('../apps/worker/src/agent-skill-bundle.ts', import.meta.url);
const generated = '// Generated by scripts/bundle-agent-skills.mjs. Update the source catalog and regenerate.\n' +
  `export const skillRevision = ${JSON.stringify(revision)};\n` +
  `export const bundledAgentSkills = ${JSON.stringify(roles, null, 2)} as const;\n`;
if (args[0] === '--check') {
  if (readFileSync(output, 'utf8') !== generated) throw new Error('The bundled runtime guidance differs from the pinned catalog revision');
} else writeFileSync(output, generated);
